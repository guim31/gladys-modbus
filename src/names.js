/**
 * A feature name in one language, with an occurrence number when a device
 * has several of the same (two meters behind one SunSpec inverter).
 */
export function featureName(key, lang, occurrence = 1) {
  const name = (NAMES[lang] ?? NAMES.en)[key] ?? NAMES.en[key] ?? key;
  return occurrence > 1 ? `${name} ${occurrence}` : name;
}
